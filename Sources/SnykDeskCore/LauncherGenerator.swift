import Foundation

public enum LauncherStatus: Equatable, Sendable {
    /// No launcher in the folder yet.
    case missing
    /// A Snyk Desk launcher is already there.
    case installed
    /// A different file with the launcher's name is there.
    case foreign
}

/// Builds the shell launcher that runs the Snyk CLI for each repository.
/// The app and the launchd schedule both run this one script, so manual and
/// scheduled scans behave the same way.
public enum LauncherGenerator {
    public static let excludes = "node_modules,target,build,.dart_tool,Pods,.venv,venv,dist"

    public static func shellQuote(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    public static func entry(for repo: RepoConfig, resultsFolder: String) -> String {
        func flag(_ value: Bool) -> String { value ? "1" : "0" }
        let name = repo.name.replacingOccurrences(of: "|", with: "/")
        return [repo.id.uuidString, name, repo.path,
                flag(repo.scanDependencies), flag(repo.scanCode), flag(repo.monitor), flag(repo.scheduled),
                resultsFolder]
            .joined(separator: "|")
    }

    public static func script(config: AppConfig, snykPath: String, pathEnv: String, javaHome: String? = nil) -> String {
        let entries = config.repos
            .map { ($0, ResultsLocation.folder(for: $0, config: config)) }
            .filter { !$0.0.path.contains("|") && !$0.1.contains("|") }
            .map { "  " + shellQuote(entry(for: $0.0, resultsFolder: $0.1)) }
            .joined(separator: "\n")
        let javaLine = javaHome.map { "export JAVA_HOME=\(shellQuote($0))" }
            ?? "# JAVA_HOME comes from the environment (Snyk Desk has not installed its own Java)."
        return #"""
        #!/bin/bash
        # \#(Paths.launcherMarker) v4
        # Generated by Snyk Desk (https://github.com/bodco/snyk-desk).
        # Do not edit: the app rewrites this file whenever its settings change.
        # Usage: snyk-desk-scan.sh [--scheduled] [repo-id ...]
        #   Without ids it scans the repositories that are in the schedule.
        #   Each scan goes to <results folder of the repo>/<timestamp>/.

        SNYK=\#(shellQuote(snykPath))
        export PATH=\#(shellQuote(pathEnv))
        \#(javaLine)
        EXCLUDES=\#(shellQuote(excludes))
        TS="$(date +%Y-%m-%dT%H-%M-%S)"
        MODE=manual
        if [ "$1" = "--scheduled" ]; then MODE=scheduled; shift; fi

        REPOS=(
        \#(entries)
        )

        tool_version() {
          # tool_version <command> <args...>: first line of the version, or "not found"
          command -v "$1" > /dev/null 2>&1 || { echo "not found"; return; }
          "$@" 2>&1 | grep -v -E "JAVA_TOOL_OPTIONS|_JAVA_OPTIONS" | head -1
        }

        slog() {
          # slog <out-dir> <message...>: one line in <out-dir>/scan.log
          local out="$1"
          shift
          echo "[$(date '+%H:%M:%S')] $*" >> "$out/scan.log"
        }

        run_step() {
          # run_step <out-dir> <step> <command...>
          local out="$1" step="$2"
          shift 2
          echo "::step $step"
          slog "$out" "$step: start: ${*/--json-file-output=*/--json-file-output=...}"
          local began=$SECONDS
          "$@" > "$out/$step.log" 2>&1
          local rc=$?
          if [ "$step" = "monitor" ] && [ "$rc" = "2" ] && grep -q "Explore this snapshot" "$out/$step.log"; then
            # Snyk monitored the main project and failed only on some sub-projects.
            echo "Some sub-projects could not be monitored. The main project was. See monitor.log." > "$out/$step.note"
            slog "$out" "$step: partial success, treated as done with a note"
            rc=0
          fi
          echo "$rc" > "$out/$step.exit"
          slog "$out" "$step: exit $rc after $((SECONDS - began)) s"
          echo "::exit $step $rc"
          return $rc
        }

        skip_step() {
          # skip_step <out-dir> <step> <reason>: records why a step could not run
          local out="$1" step="$2" reason="$3"
          echo "::step $step"
          echo "$reason" > "$out/$step.log"
          slog "$out" "$step: skipped: $reason"
          echo "2" > "$out/$step.exit"
          echo "::exit $step 2"
        }

        preflight() {
          # Prints a plain reason when the build tools this repository needs are missing.
          if [ -f pom.xml ]; then
            command -v mvn > /dev/null 2>&1 || { echo "Maven (mvn) was not found. Open Snyk Desk, Settings, Tools, and install it."; return; }
            mvn -v > /dev/null 2>&1 || { echo "Maven is installed but does not run, usually because Java is missing. Open Snyk Desk, Settings, Tools, and install Java."; return; }
          fi
          if { [ -f build.gradle ] || [ -f build.gradle.kts ]; } && [ ! -x ./gradlew ]; then
            command -v gradle > /dev/null 2>&1 || { echo "Gradle was not found and the repository has no gradlew. Open Snyk Desk, Settings, Tools, and install it."; return; }
          fi
          if [ -f package.json ] && [ ! -f package-lock.json ] && [ ! -f yarn.lock ] && [ ! -f pnpm-lock.yaml ]; then
            command -v node > /dev/null 2>&1 || { echo "Node.js was not found and the repository has no lock file. Open Snyk Desk, Settings, Tools, and install it."; return; }
          fi
          if [ -f go.mod ]; then
            command -v go > /dev/null 2>&1 || { echo "Go was not found. Open Snyk Desk, Settings, Tools, and install it."; return; }
          fi
        }

        scan_repo() {
          local id="$1" name="$2" path="$3" deps="$4" code="$5" mon="$6" results="$7"
          local out="$results/$TS"
          mkdir -p "$out"
          echo "::repo $id $name"
          slog "$out" "repo: $name ($path), mode $MODE, deps=$deps code=$code monitor=$mon"
          slog "$out" "snyk: $("$SNYK" --version 2>&1 | head -1) at $SNYK"
          slog "$out" "PATH: $PATH"
          slog "$out" "JAVA_HOME: ${JAVA_HOME:-not set}"
          if [ ! -d "$path" ]; then
            slog "$out" "folder not found"
            echo "Folder not found: $path" > "$out/error.txt"
            date +%s > "$out/finished"
            echo "::done $id"
            return
          fi
          cd "$path" || return
          {
            echo "[$(date '+%H:%M:%S')] tools:"
            echo "  java: $(tool_version java -version)"
            echo "  mvn: $(tool_version mvn -v)"
            echo "  node: $(tool_version node -v)"
            echo "  go: $(tool_version go version)"
            echo "  uv: $(tool_version uv --version)"
            echo "  git branch: $(git rev-parse --abbrev-ref HEAD 2>&1 | head -1)"
            echo "  files: $(ls -1A | head -30 | tr '\n' ' ')"
          } >> "$out/scan.log"
          local scope hint
          hint="$(preflight)"
          if [ -f pom.xml ] && grep -q "<modules>" pom.xml; then
            # One aggregated Maven test instead of one test per pom.xml.
            scope=(--maven-aggregate-project)
          else
            scope=(--all-projects "--exclude=$EXCLUDES")
          fi
          if [ "$deps" = "1" ]; then
            if [ -n "$hint" ]; then
              skip_step "$out" deps "$hint"
            else
              if ! run_step "$out" deps "$SNYK" test "${scope[@]}" "--json-file-output=$out/deps.json" \
                 && [ -f pom.xml ] && grep -q "SNYK-OS-MAVEN-0018" "$out/deps.log"; then
                # Snyk hides the real reason; ask Maven itself.
                slog "$out" "deps: Maven failed, running mvn to capture the real error (maven.log)"
                mvn -B dependency:tree > "$out/maven.log" 2>&1
                slog "$out" "mvn dependency:tree exit $?"
              fi
            fi
          fi
          if [ "$code" = "1" ]; then
            run_step "$out" code "$SNYK" code test "--sarif-file-output=$out/code.json"
          fi
          if [ "$mon" = "1" ]; then
            local ref
            ref="$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo main)"
            if [ -n "$hint" ]; then
              skip_step "$out" monitor "$hint"
            else
              run_step "$out" monitor "$SNYK" monitor "${scope[@]}" "--target-reference=$ref"
            fi
          fi
          date +%s > "$out/finished"
          slog "$out" "finished"
          echo "::done $id"
        }

        COUNT=0
        for entry in "${REPOS[@]}"; do
          IFS='|' read -r id name path deps code mon sched results <<< "$entry"
          if [ $# -gt 0 ]; then
            match=0
            for want in "$@"; do
              if [ "$want" = "$id" ]; then match=1; fi
            done
            [ "$match" = "1" ] || continue
          else
            [ "$sched" = "1" ] || continue
          fi
          ( scan_repo "$id" "$name" "$path" "$deps" "$code" "$mon" "$results" )
          COUNT=$((COUNT + 1))
        done

        echo "::finished $COUNT"
        if [ "$MODE" = "scheduled" ]; then
          /usr/bin/osascript -e "display notification \"Scanned $COUNT repositories\" with title \"Snyk Desk\"" > /dev/null 2>&1
        fi

        """#
    }

    public static func url(in folder: String) -> URL {
        URL(fileURLWithPath: folder).appendingPathComponent(Paths.launcherName)
    }

    public static func status(in folder: String) -> LauncherStatus {
        let file = url(in: folder)
        guard FileManager.default.fileExists(atPath: file.path) else { return .missing }
        guard let text = try? String(contentsOf: file, encoding: .utf8) else { return .foreign }
        return text.contains(Paths.launcherMarker) ? .installed : .foreign
    }

    @discardableResult
    public static func install(config: AppConfig, folder: String, snykPath: String, pathEnv: String,
                               javaHome: String? = nil) throws -> URL {
        let file = url(in: folder)
        Paths.ensure(URL(fileURLWithPath: folder))
        let text = script(config: config, snykPath: snykPath, pathEnv: pathEnv, javaHome: javaHome)
        try text.write(to: file, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: file.path)
        return file
    }
}
